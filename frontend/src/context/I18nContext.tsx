interface I18nContextType {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: string) => string
  /** Where the site's own words are at: 'english' needs no translating at all. */
  chromeState: 'english' | 'cached' | 'loading' | 'failed'
  /** Changes whenever the reader's language changes, so pages can reload. */
  languageVersion: number
}

const I18nContext = createContext<I18nContextType | undefined>(undefined)

const ENGLISH = translations.en

// What this browser already knows about the language it is about to show.
function starting(lang: Lang): { labels: Translations; state: 'english' | 'cached' | 'loading' } {
  if (lang === DEFAULT_LANGUAGE) return { labels: {}, state: 'english' }
  const stored = cachedChromeLabels(lang, ENGLISH)
  return stored ? { labels: stored, state: 'cached' } : { labels: {}, state: 'loading' }
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => readerLanguage())
  const [labels, setLabels] = useState<Translations>(() => starting(lang).labels)
  const [chromeState, setChromeState] = useState<'english' | 'cached' | 'loading' | 'failed'>(() => starting(lang).state)
  const [languageVersion, setLanguageVersion] = useState(0)

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  // The reader may change the language from the picker, the settings page or
  // another tab; all of them go through the same store.
  useEffect(() => subscribeToReaderLanguage(() => setLangState(readerLanguage())), [])

  useEffect(() => {
    if (lang === DEFAULT_LANGUAGE) {
      setLabels({})
      setChromeState('english')
      return
    }
    const stored = cachedChromeLabels(lang, ENGLISH)
    if (stored) {
      setLabels(stored)
      setChromeState('cached')
      return
    }
    // This language has never been asked for on this browser. Ask once, and keep
    // reading English until the answer arrives - never a blank page and never a
    // key name where a word should be.
    let live = true
    setLabels({})
    setChromeState('loading')
    translateAPI
      .translateChrome(lang, ENGLISH)
      .then((result) => {
        if (!live) return
        if (result.translated && Object.keys(result.strings).length) {
          rememberChromeLabels(lang, ENGLISH, result.strings)
          setLabels(result.strings)
          setChromeState('cached')
        } else {
          setChromeState('failed')
        }
      })
      .catch(() => {
        if (live) setChromeState('failed')
      })
    return () => {
      live = false
    }
  }, [lang])

  const setLang = (next: Lang) => {
    const code = String(next || '').trim()
    if (!code) return
    setReaderLanguage(code)
    markLanguageAnswered()
    setLangState(code)
    setLanguageVersion((version) => version + 1)
  }

  // English is the copy the site is written in, so a label the translator has
  // not answered for yet falls back to it rather than to the key itself.
  const t = useCallback((key: string) => labels[key] || ENGLISH[key] || key, [labels])

  return (
    <I18nContext.Provider value={{ lang, setLang, t, chromeState, languageVersion }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}
